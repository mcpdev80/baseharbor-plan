def cmd_check(root):
    vault = Vault(root).load().validate()
    for w in vault.warnings:
        print("warning:", w)
    for e in vault.errors:
        print("error:", e)
    print(f"{len(vault.tasks)} tasks, {len(vault.epics)} epics, {len(vault.releases)} releases, "
          f"{len(vault.decisions)} decisions; {len(vault.errors)} errors, {len(vault.warnings)} warnings")
    return 1 if vault.errors else 0


def cmd_list(root, args):
    vault = Vault(root).load()
    for t in sorted(vault.tasks.values(), key=task_sort):
        st = derived_state(vault, t)
        if args.ready and st != "ready":
            continue
        if args.status and st != args.status:
            continue
        if args.release and t["release"] != args.release:
            continue
        if args.owner and args.owner.lower() not in t["owner"].lower():
            continue
        print(f"{t['id']:<22} {st:<9} {t['release']:<8} {t['title']}  [{vault.rel(t['path'])}]")
    return 0


def cmd_show(root, args):
    vault = Vault(root).load()
    t = vault.tasks.get(args.id)
    if not t:
        print(f"unknown task {args.id}", file=sys.stderr)
        return 1
    print(vault.rel(t["path"]))
    print("state:", derived_state(vault, t))
    for dep in t["depends_on"]:
        print(f"  depends on {dep}: {'accepted' if vault.accepted(dep) else 'NOT accepted'}")
    return 0


def cmd_new(root, args):
    today = datetime.date.today().strftime("%Y%m%d")
    tid = f"t-{today}-{args.slug}"
    if not NEW_ID.match(tid):
        print("slug must be lowercase words joined by '-'", file=sys.stderr)
        return 1
    path = root / "tasks" / f"{tid}.md"
    if path.exists():
        print(f"{path} exists", file=sys.stderr)
        return 1
    template = (root / "templates" / "task.md").read_text(encoding="utf-8")
    status = "backlog" if args.release in ("backlog", "triage") else "planned"
    existing = Vault(root).load()
    prefix = card_release_prefix({"release": args.release, "version": args.version or ""})
    number = ""
    if prefix:
        used = [int(as_str(x["meta"].get("card_number")).split("-")[1])
                for x in existing.tasks.values()
                if as_str(x["meta"].get("card_number")).startswith(prefix + "-")
                and CARD_NUMBER.fullmatch(as_str(x["meta"].get("card_number")))]
        seq = max(used, default=0) + 1
        if seq > 999:
            print("card number range exhausted for this release", file=sys.stderr)
            return 1
        number = f"{prefix}-{seq:03d}"
    text = (template.replace("{{card_number}}", number)
            .replace("{{card_short_title}}", compact_card_title(args.title) if number else "")
            .replace("{{id}}", tid).replace("{{title}}", args.title)
            .replace("version: \"\"", "version: " + dump_value(args.version or ""), 1)
            .replace("{{release}}", args.release).replace("{{release_tag}}", release_tag(args.release))
            .replace("{{status}}", status).replace("{{repo}}", REPO_PREFIX[args.repo]))
    path.write_text(text, encoding="utf-8")
    print(vault_rel(root, path))
    print("Fill in the sections, then run: python3 scripts/plan.py render && python3 scripts/plan.py check")
    return 0


def cmd_claim(root, args):
    vault = Vault(root).load()
    t = vault.tasks.get(args.id)
    if not t:
        print(f"unknown task {args.id}", file=sys.stderr)
        return 1
    if t["done"] or t["status"] not in ("planned", "wait", "blocked"):
        print(f"{args.id} is {derived_state(vault, t)}; only planned, wait or blocked tasks can be claimed", file=sys.stderr)
        return 1
    if t["owner"] and t["owner"] != args.owner and not args.force:
        print(f"{args.id} already has owner {t['owner']!r}; coordinate first (or --force after agreement)",
              file=sys.stderr)
        return 1
    text = t["path"].read_text(encoding="utf-8")
    text = re.sub(r"(?m)^owner:.*$", "owner: " + dump_value(args.owner), text, count=1)
    text = re.sub(r"(?m)^blocker:.*$", 'blocker: ""', text, count=1)
    text = re.sub(r"(?m)^wait_reason:.*$", 'wait_reason: ""', text, count=1)
    if "kanban_status" in t["meta"]:
        text = re.sub(r"(?m)^kanban_status:.*$", "kanban_status: active", text, count=1)
    if "kanban_lane" in t["meta"]:
        text = re.sub(r"(?m)^kanban_lane:.*$", "kanban_lane: active", text, count=1)
    lines = text.split("\n")
    for i, l in enumerate(lines):
        if CARD.match(l):
            lines[i] = re.sub(r"#status/\S+", "#status/active", l)
            break
    t["path"].write_text("\n".join(lines), encoding="utf-8")
    render(Vault(root).load())
    print(f"claimed {args.id}; now commit and push before editing code:")
    print(f"  git commit -am 'claim {args.id}: {args.owner}' && git push")
    return 0


def vault_rel(root, path):
    return str(path.relative_to(root))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
