# ---------------------------------------------------------------- frontmatter

def parse_frontmatter(text):
    """Parse the YAML subset used in this vault: scalars, flow lists and block lists."""
    if not text.startswith("---\n"):
        raise ValueError("missing frontmatter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ValueError("unterminated frontmatter")
    block, body = text[4:end], text[end + 5:]
    data, key = {}, None
    for lineno, line in enumerate(block.split("\n"), 2):
        if not line.strip():
            continue
        item = re.match(r"^\s+- (.*)$", line) or re.match(r"^- (.*)$", line)
        if item and key is not None and isinstance(data[key], list):
            data[key].append(scalar(item.group(1)))
            continue
        m = re.match(r"^([a-z_]+):(?: (.*))?$", line)
        if not m:
            raise ValueError(f"unsupported frontmatter line {lineno}: {line!r}")
        key, raw = m.group(1), (m.group(2) or "").strip()
        if key in data:
            raise ValueError(f"duplicate frontmatter key {key!r}")
        if raw == "":
            data[key] = []
        elif raw.startswith("["):
            if not raw.endswith("]"):
                raise ValueError(f"unterminated list for {key!r}")
            inner = raw[1:-1].strip()
            data[key] = [scalar(v) for v in split_flow(inner)] if inner else []
        else:
            data[key] = scalar(raw)
    return data, body


def split_flow(inner):
    parts, cur, quote = [], "", None
    for ch in inner:
        if quote:
            cur += ch
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
            cur += ch
        elif ch == ",":
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    parts.append(cur.strip())
    return parts


def scalar(raw):
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'":
        return raw[1:-1]
    if re.fullmatch(r"-?\d+", raw):
        return int(raw)
    return raw


def as_list(value):
    if value in (None, ""):
        return []
    return value if isinstance(value, list) else [value]


def as_str(value):
    if value in (None, []):
        return ""
    return str(value)


def dump_value(value):
    if isinstance(value, list):
        return "[" + ", ".join(quote(v) for v in value) + "]"
    return quote(value)


def quote(value):
    s = str(value)
    if s == "" or re.search(r"[:#\[\]{},&*!|>'\"%@`]", s) or s.strip() != s:
        return json.dumps(s, ensure_ascii=False)
    return s


# ---------------------------------------------------------------- model

class Vault:
    def __init__(self, root):
        self.root = root
        self.errors = []
        self.warnings = []
        self.tasks = {}
        self.releases = {}
        self.epics = {}
        self.decisions = {}
        self.docs = {}  # every markdown file with frontmatter sources, by path

    def err(self, path, msg):
        self.errors.append(f"{self.rel(path)}: {msg}")

    def warn(self, path, msg):
        self.warnings.append(f"{self.rel(path)}: {msg}")

    def rel(self, path):
        try:
            return str(pathlib.Path(path).relative_to(self.root))
        except ValueError:
            return str(path)

    def load(self):
        for folder, store, loader in (
            ("releases", self.releases, self.load_release),
            ("epics", self.epics, self.load_epic),
            ("decisions", self.decisions, self.load_decision),
            ("tasks", self.tasks, self.load_task),
        ):
            for path in sorted((self.root / folder).glob("*.md")):
                try:
                    meta, body = parse_frontmatter(path.read_text(encoding="utf-8"))
                except ValueError as exc:
                    self.err(path, str(exc))
                    continue
                item = loader(path, meta, body)
                if item is None:
                    continue
                if item["id"] in store:
                    self.err(path, f"duplicate id {item['id']} (also {self.rel(store[item['id']]['path'])})")
                    continue
                store[item["id"]] = item
        for path in sorted(self.root.glob("*.md")) + sorted((self.root / "migration").glob("*.md")):
            text = path.read_text(encoding="utf-8")
            if text.startswith("---\n"):
                try:
                    meta, body = parse_frontmatter(text)
                except ValueError as exc:
                    self.err(path, str(exc))
                    continue
                if "sources" in meta:
                    self.docs[path] = {"path": path, "kind": as_str(meta.get("kind")) or "document",
                                       "sources": as_list(meta.get("sources"))}
        return self

    def load_release(self, path, meta, body):
        rid = as_str(meta.get("id"))
        if path.stem != rid:
            self.err(path, f"release file name must equal its id {rid!r}")
        kind = as_str(meta.get("kind"))
        if kind not in RELEASE_KINDS:
            self.err(path, f"kind must be one of {RELEASE_KINDS}")
        status = as_str(meta.get("status"))
        if status not in RELEASE_STATUSES:
            self.err(path, f"status must be one of {RELEASE_STATUSES}")
        if not isinstance(meta.get("order"), int):
            self.err(path, "order must be an integer")
        item = {"id": rid, "path": path, "kind": kind, "status": status, "order": meta.get("order", 0),
                "title": as_str(meta.get("title")), "sources": as_list(meta.get("sources")),
                "evidence": as_list(meta.get("evidence"))}
        if status in ("qualified", "published") and not item["evidence"]:
            self.err(path, f"release status {status} requires evidence links")
        self.docs[path] = {"path": path, "kind": "release", "sources": item["sources"]}
        return item

    def load_epic(self, path, meta, body):
        eid = as_str(meta.get("id"))
        self.check_id(path, eid)
        status = as_str(meta.get("status"))
        if status not in EPIC_STATUSES:
            self.err(path, f"status must be one of {EPIC_STATUSES}")
        item = {"id": eid, "path": path, "status": status, "title": as_str(meta.get("title")),
                "release": as_str(meta.get("release")), "parent": as_str(meta.get("parent")),
                "sources": as_list(meta.get("sources"))}
        self.docs[path] = {"path": path, "kind": "epic", "sources": item["sources"]}
        return item

    def load_decision(self, path, meta, body):
        did = as_str(meta.get("id"))
        if path.stem != did:
            self.err(path, f"decision file name must equal its id {did!r}")
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}-[a-z0-9-]+", did):
            self.err(path, "decision id must be YYYY-MM-DD-slug")
        if as_str(meta.get("status")) not in ("proposed", "accepted", "superseded"):
            self.err(path, "decision status must be proposed, accepted or superseded")
        item = {"id": did, "path": path, "sources": as_list(meta.get("sources"))}
        self.docs[path] = {"path": path, "kind": "decision", "sources": item["sources"]}
        return item

    def check_id(self, path, tid):
        if not (MIGRATED_ID.match(tid) or NEW_ID.match(tid)):
            self.err(path, f"invalid id {tid!r}")
        if not path.stem.startswith(tid + "-") and path.stem != tid:
            self.err(path, f"file name must start with its id {tid!r}")

    def load_task(self, path, meta, body):
        tid = as_str(meta.get("id"))
        self.check_id(path, tid)
        lines = body.split("\n")
        cards = [(i, l) for i, l in enumerate(lines) if CHECKBOX.match(l)]
        if len(cards) != 1:
            self.err(path, f"a task note must contain exactly one checkbox (found {len(cards)})")
            return None
        idx, line = cards[0]
        if line != line.lstrip():
            self.err(path, "the task checkbox must not be indented")
        m = CARD.match(line)
        if not m:
            self.err(path, "card line must be '- [ ] <id> · <title> #task #release/<r> #status/<s>'")
            return None
        tags = m.group("tags").split()
        status_tags = [t[len("#status/"):] for t in tags if t.startswith("#status/")]
        release_tags = [t[len("#release/"):] for t in tags if t.startswith("#release/")]
        done = m.group("done") != " "
        item = {
            "id": tid, "path": path, "title": m.group("title").strip(), "done": done,
            "status": status_tags[0] if len(status_tags) == 1 else "",
            "card_line": idx, "body": body, "meta": meta,
            "type": as_str(meta.get("type")) or "task",
            "release": as_str(meta.get("release")), "version": as_str(meta.get("version")),
            "parent": as_str(meta.get("parent")), "owner": as_str(meta.get("owner")),
            "depends_on": as_list(meta.get("depends_on")), "repos": as_list(meta.get("repos")),
            "prs": as_list(meta.get("prs")), "sources": as_list(meta.get("sources")),
            "blocker": as_str(meta.get("blocker")), "resolution": as_str(meta.get("resolution")),
            "evidence": as_list(meta.get("evidence")), "superseded_by": as_str(meta.get("superseded_by")),
            "aliases": as_list(meta.get("aliases")),
            "early": meta.get("early", "false") == "true",
        }
        if as_str(meta.get("early")) not in ("", "true", "false"):
            self.err(path, "early must be true or false")
        if m.group("id") != tid:
            self.err(path, f"card id {m.group('id')!r} differs from frontmatter id {tid!r}")
        if "#task" not in tags:
            self.err(path, "card must carry #task")
        unknown = [t for t in tags if t != "#task" and not t.startswith(("#status/", "#release/"))]
        if unknown:
            self.err(path, f"card carries unsupported tags {unknown}; keep metadata in frontmatter")
        if len(release_tags) != 1:
            self.err(path, "card must carry exactly one #release/<r> tag")
        elif "release/" + release_tags[0] != release_tag(item["release"]):
            self.err(path, f"card tag #release/{release_tags[0]} does not match release {item['release']!r}"
                           f" (expected #{release_tag(item['release'])})")
        if done:
            if status_tags != [CLOSED]:
                self.err(path, "conflicting lifecycle markers: a checked card must carry exactly #status/closed;"
                               f" found {['#status/' + s for s in status_tags]} — replace it and record resolution"
                               " and evidence")
            if item["resolution"] not in RESOLUTIONS:
                self.err(path, f"a checked card requires resolution in {RESOLUTIONS}")
            if not item["evidence"]:
                self.err(path, "a checked card requires evidence links (a checkbox alone is not acceptance)")
            if item["resolution"] == "superseded" and not item["superseded_by"]:
                self.err(path, "resolution superseded requires superseded_by")
        else:
            if len(status_tags) != 1:
                self.err(path, f"an open card needs exactly one #status tag from {STATUSES}")
            elif status_tags[0] == CLOSED:
                self.err(path, "conflicting lifecycle markers: #status/closed on an unchecked card")
            elif status_tags[0] not in STATUSES:
                self.err(path, f"unknown status {status_tags[0]!r}; use one of {STATUSES}")
            if item["resolution"]:
                self.err(path, "resolution is only valid on a checked card")
        if m.group("completed") and not done:
            self.err(path, "@completed marker on an unchecked card")
        if item["type"] not in TASK_TYPES:
            self.err(path, f"type must be one of {TASK_TYPES}")
        st = item["status"]
        if st in ("active", "review") and not item["owner"]:
            self.err(path, f"status {st} requires an owner")
        if st == "review" and not item["prs"]:
            self.err(path, "status review requires at least one PR")
        if st == "blocked" and not item["blocker"]:
            self.err(path, "status blocked requires a blocker description")
        if st != "blocked" and item["blocker"] and not done:
            self.err(path, "blocker is set but the card is not #status/blocked")
        if st == "backlog" and item["release"] not in ("backlog", "triage"):
            self.err(path, "#status/backlog is only valid for release backlog or triage")
        for ref in item["prs"] + item["sources"] + item["aliases"]:
            if not SOURCE_REF.match(str(ref)):
                self.err(path, f"invalid repository reference {ref!r}; use owner/repo#number")
        for ref in item["evidence"]:
            if not str(ref).startswith("https://"):
                self.err(path, f"evidence must be https links, got {ref!r}")
        for repo in item["repos"]:
            if repo not in REPO_PREFIX.values():
                self.err(path, f"unknown repository {repo!r}")
        if not item["repos"]:
            self.err(path, "repos must list at least one affected repository")
        if MIGRATED_ID.match(tid):
            prefix, num = tid.split("-")[0], tid.split("-")[1]
            expected = f"{REPO_PREFIX[prefix]}#{num}"
            if expected not in item["sources"]:
                self.err(path, f"migrated id {tid} must list {expected} in sources")
        for i, l in enumerate(lines):
            if i != idx and re.search(r"(^|\s)#status/", l):
                self.err(path, f"#status tag outside the card line (line {i + 1} of body)")
        self.docs[path] = {"path": path, "kind": "task", "sources": item["sources"], "aliases": item["aliases"]}
        return item

    # ------------------------------------------------------------ cross checks

    def validate(self):
        ids = set(self.tasks)
        for tid in set(self.tasks) & set(self.epics):
            self.err(self.tasks[tid]["path"], f"id {tid} is used by both a task and an epic")
        parents = set(self.epics) | set(self.releases)
        for t in self.tasks.values():
            if t["release"] not in self.releases:
                self.err(t["path"], f"unknown release {t['release']!r}")
            if t["parent"] and t["parent"] not in parents:
                self.err(t["path"], f"unknown parent {t['parent']!r}")
            for dep in t["depends_on"]:
                if dep not in ids:
                    self.err(t["path"], f"unknown dependency {dep!r}")
                if dep == t["id"]:
                    self.err(t["path"], "task depends on itself")
            if t["superseded_by"] and t["superseded_by"] not in ids:
                self.err(t["path"], f"unknown superseded_by {t['superseded_by']!r}")
            open_deps = [d for d in t["depends_on"] if d in ids and not self.accepted(d)]
            if t["status"] in ("active", "review") and open_deps:
                self.warn(t["path"], f"{t['status']} although dependencies are not accepted: {open_deps}")
            if t["done"] and t["resolution"] == "accepted" and open_deps:
                self.warn(t["path"], f"accepted although dependencies are not accepted: {open_deps}")
        for e in self.epics.values():
            if e["release"] and e["release"] not in self.releases:
                self.err(e["path"], f"unknown release {e['release']!r}")
            if e["parent"] and e["parent"] not in parents:
                self.err(e["path"], f"unknown parent {e['parent']!r}")
        self.check_cycles()
        self.check_links()
        self.check_stray_checkboxes()
        self.check_generated_blocks()
        self.check_sources()
        self.check_cardboard()
        self.check_git_settings()
        return self

    def accepted(self, tid):
        t = self.tasks.get(tid)
        if not t or not t["done"]:
            return False
        if t["resolution"] == "accepted":
            return True
        if t["resolution"] == "superseded":
            return self.accepted(t["superseded_by"])
        return False

    def check_cycles(self):
        state = {}

        def visit(tid, stack):
            state[tid] = 1
            for dep in self.tasks[tid]["depends_on"]:
                if dep not in self.tasks:
                    continue
                if state.get(dep) == 1:
                    cycle = stack[stack.index(dep):] + [dep]
                    self.err(self.tasks[tid]["path"], "dependency cycle: " + " -> ".join(cycle))
                elif state.get(dep) is None:
                    visit(dep, stack + [dep])
            state[tid] = 2

        for tid in sorted(self.tasks):
            if state.get(tid) is None:
                visit(tid, [tid])

    def markdown_files(self):
        skip = ("migration/source-snapshot", "scripts/tests/fixtures", ".obsidian", ".git", "node_modules")
        for path in sorted(self.root.rglob("*.md")):
            rel = self.rel(path)
            if rel.startswith(skip):
                continue
            yield path

    def check_links(self):
        link = re.compile(r"(?<!!)\[[^\]]*\]\(([^)\s]+)\)")
        for path in self.markdown_files():
            text = path.read_text(encoding="utf-8")
            text = re.sub(r"```.*?```", "", text, flags=re.S)
            text = re.sub(r"`[^`\n]*`", "", text)
            for target in link.findall(text):
                if re.match(r"^[a-z]+:", target) or target.startswith("#"):
                    continue
                dest = (path.parent / target.split("#")[0]).resolve()
                if not dest.exists():
                    self.err(path, f"broken link {target!r}")
            for wl in re.findall(r"\[\[([^\]|#]+)", text):
                if not list(self.root.rglob(wl.strip() + ".md")) and not (self.root / wl.strip()).exists():
                    self.err(path, f"broken wiki link [[{wl}]]")

    def check_stray_checkboxes(self):
        for path in self.markdown_files():
            rel = self.rel(path)
            if rel.startswith("tasks/"):
                continue
            for i, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
                if TOP_CHECKBOX.match(line) and not rel.startswith("templates/"):
                    self.err(path, f"checkbox outside tasks/ would become a CardBoard card (line {i})")

    def check_generated_blocks(self):
        for t in self.tasks.values():
            want = links_block(self, t)
            have = extract_block(t["body"])
            if have is None:
                self.err(t["path"], "missing generated links block; run scripts/plan.py render")
            elif have != want:
                self.err(t["path"], "generated links block is stale; run scripts/plan.py render")
        for path, content in render_views(self).items():
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                self.err(path, "generated file is stale; run scripts/plan.py render")

    def check_sources(self):
        inv_path = SNAPSHOT / "inventory.json"
        if not inv_path.exists():
            self.err(inv_path, "missing source inventory")
            return
        inventory = json.loads(inv_path.read_text(encoding="utf-8"))
        inventoried = {e["source"]: e for e in inventory["open_issues"]}
        for e in inventoried.values():
            f = self.root / e["file"]
            if not f.exists():
                self.err(f, "snapshot file listed in the inventory is missing")
            elif hashlib.sha256(f.read_bytes()).hexdigest() != e["sha256"]:
                self.err(f, "snapshot file does not match its inventory digest")
        mapped = {}
        for doc in self.docs.values():
            for src in doc["sources"] + doc.get("aliases", []):
                if src not in inventoried:
                    self.err(doc["path"], f"source {src} is not in the open-issue inventory")
                mapped.setdefault(src, []).append(doc)
        for src in sorted(set(inventoried) - set(mapped), key=source_key):
            self.err(inv_path, f"open issue {src} is not accounted for by any destination")

    def check_cardboard(self):
        if not CARDBOARD_SETTINGS.exists():
            self.err(CARDBOARD_SETTINGS, "missing CardBoard settings")
            return
        for problem in validate_cardboard(json.loads(CARDBOARD_SETTINGS.read_text(encoding="utf-8")),
                                          {release_tag(r) for r in self.releases}):
            self.err(CARDBOARD_SETTINGS, problem)

    def check_git_settings(self):
        if not GIT_SETTINGS.exists():
            self.err(GIT_SETTINGS, "missing Obsidian Git settings")
            return
        cfg = json.loads(GIT_SETTINGS.read_text(encoding="utf-8"))
        for key in ("autoSaveInterval", "autoPushInterval", "autoPullInterval"):
            if cfg.get(key) != 0:
                self.err(GIT_SETTINGS, f"{key} must be 0 (manual commits, pulls and pushes)")
        for key in ("autoPullOnBoot", "autoBackupAfterFileChange", "squashCommitsBeforePush"):
            if cfg.get(key) is not False:
                self.err(GIT_SETTINGS, f"{key} must be false")
        if cfg.get("syncMethod") != "merge":
            self.err(GIT_SETTINGS, "syncMethod must be merge (never rewrite published history)")


def release_tag(release_id):
    return "release/" + release_id.replace(".", "-")


def source_key(src):
    repo, num = src.split("#")
    order = list(REPO_PREFIX.values())
    return (order.index(repo) if repo in order else 99, int(num))


def gh_url(ref):
    repo, num = ref.split("#")
    return f"https://github.com/{repo}/issues/{num}"


def short_ref(ref):
    repo, num = ref.split("#")
    return f"{repo.split('/')[1]}#{num}"


# ---------------------------------------------------------------- CardBoard schema (settings 0.13.0)

def validate_cardboard(cfg, release_tags):
    problems = []
    if cfg.get("version") != "0.13.0":
        problems.append("settings version must be 0.13.0 (CardBoard 0.7.9)")
    data = cfg.get("data", {})
    gs = data.get("globalSettings", {})
    need_gs = {"defaultColumnNames", "filters", "firstDayOfWeek", "ignoreFileNameDates",
               "taskCompletionFormat", "taskCompletionInLocalTime", "taskCompletionShowUtcOffset"}
    if set(gs) != need_gs:
        problems.append(f"globalSettings keys must be exactly {sorted(need_gs)}")
    if gs.get("taskCompletionFormat") not in ("ObsidianCardBoard", "ObsidianDataview", "ObsidianTasks", "NoCompletion"):
        problems.append("unsupported taskCompletionFormat")
    for f in gs.get("filters", []):
        if f.get("tag") not in ("pathFilter", "fileFilter", "tagFilter"):
            problems.append(f"unsupported global filter {f}")
    ignored = {f.get("data") for f in gs.get("filters", []) if f.get("tag") == "pathFilter"}
    for folder in ("templates", "migration", "views", "decisions", "releases", "epics", "scripts"):
        if folder not in ignored:
            problems.append(f"global path filter must ignore {folder}/ to prevent accidental cards")
    column_keys = {
        "namedTag": {"collapsed", "name", "tag"}, "otherTags": {"collapsed", "name"},
        "untagged": {"collapsed", "name"}, "undated": {"collapsed", "name"},
        "completed": {"collapsed", "index", "limit", "name"}, "dated": {"collapsed", "name", "range"},
    }
    boards = data.get("boardConfigs", [])
    if not boards:
        problems.append("at least one board is required")
    for b in boards:
        name = b.get("name", "?")
        need = {"columns", "filters", "filterPolarity", "filterScope", "name", "showColumnTags", "showFilteredTags"}
        if set(b) != need:
            problems.append(f"board {name!r}: keys must be exactly {sorted(need)}")
        if b.get("filterPolarity") not in ("Allow", "Deny"):
            problems.append(f"board {name!r}: invalid filterPolarity")
        if b.get("filterScope") not in ("TopLevelOnly", "SubTasksOnly", "Both"):
            problems.append(f"board {name!r}: invalid filterScope")
        tag_filters = [f.get("data") for f in b.get("filters", []) if f.get("tag") == "tagFilter"]
        if b.get("filterPolarity") != "Allow" or not (
                "task" in tag_filters or any(t in release_tags for t in tag_filters)):
            problems.append(f"board {name!r}: must allow-filter on #task or a known #release tag")
        for t in tag_filters:
            if t != "task" and t not in release_tags and not t.startswith("status/"):
                problems.append(f"board {name!r}: filter tag {t!r} is not a known release or status tag")
        seen_singletons = set()
        for i, c in enumerate(b.get("columns", [])):
            kind = c.get("tag")
            if kind not in column_keys:
                problems.append(f"board {name!r}: unsupported column type {kind!r}")
                continue
            if set(c.get("data", {})) != column_keys[kind]:
                problems.append(f"board {name!r}: column {i} keys must be {sorted(column_keys[kind])}")
            if kind != "namedTag" and kind != "dated":
                if kind in seen_singletons:
                    problems.append(f"board {name!r}: more than one {kind} column")
                seen_singletons.add(kind)
            if kind == "completed" and c["data"].get("index") != i:
                problems.append(f"board {name!r}: completed column index must be its position {i}")
            if kind == "namedTag":
                tag = c["data"].get("tag", "")
                ok = tag in release_tags or tag.startswith("status/") and tag[len("status/"):] in STATUSES + [CLOSED]
                if not ok:
                    problems.append(f"board {name!r}: column tag {tag!r} is not a known status or release tag")
    return problems


# ---------------------------------------------------------------- derived state and rendering

ACTIVE_RELEASE_STATUSES = ("active", "candidate")


def derived_state(vault, t):
    """ready = planned, every dependency accepted, and the release has started (or the task is pulled ahead)."""
    if t["done"]:
        return t["resolution"] or "checked"
    if t["status"] == "planned":
        if any(not vault.accepted(d) for d in t["depends_on"]):
            return "waiting"
        release = vault.releases.get(t["release"], {})
        if release.get("status") in ACTIVE_RELEASE_STATUSES or t["early"]:
            return "ready"
        return "queued"
    return t["status"]


def task_link(vault, tid, from_dir):
    t = vault.tasks.get(tid) or vault.epics.get(tid)
    if not t:
        return tid
    return f"[{tid}]({relpath(t['path'], from_dir)})"


def release_link(vault, rid, from_dir):
    r = vault.releases.get(rid)
    if not r:
        return rid
    return f"[{rid}]({relpath(r['path'], from_dir)})"


def parent_link(vault, pid, from_dir):
    if pid in vault.releases:
        return release_link(vault, pid, from_dir)
    return task_link(vault, pid, from_dir)


def relpath(path, from_dir):
    import os
    return os.path.relpath(path, from_dir).replace(os.sep, "/")


def links_block(vault, t):
    d = t["path"].parent
    parts = [f"**State:** {derived_state(vault, t)}"]
    parts.append("**Release:** " + release_link(vault, t["release"], d) + (f" ({t['version']})" if t["version"] else ""))
    if t["parent"] and t["parent"] != t["release"]:
        parts.append("**Parent:** " + parent_link(vault, t["parent"], d))
    parts.append("**Depends on:** " + (", ".join(task_link(vault, x, d) for x in t["depends_on"]) or "none"))
    blocks = sorted(o["id"] for o in vault.tasks.values() if t["id"] in o["depends_on"])
    if blocks:
        parts.append("**Required by:** " + ", ".join(task_link(vault, x, d) for x in blocks))
    parts.append("**Owner:** " + (t["owner"] or "unassigned"))
    parts.append("**PRs:** " + (", ".join(f"[{short_ref(p)}]({gh_url(p).replace('/issues/', '/pull/')})"
                                         for p in t["prs"]) or "none"))
    parts.append("**Source:** " + ", ".join(f"[{short_ref(s)}]({gh_url(s)})" for s in t["sources"]))
    return "\n".join(["", "  \n".join(parts), ""])


def extract_block(body):
    a, b = body.find(GEN_BEGIN), body.find(GEN_END)
    if a < 0 or b < 0:
        return None
    return body[a + len(GEN_BEGIN):b]


def apply_block(body, block):
    a, b = body.find(GEN_BEGIN), body.find(GEN_END)
    if a >= 0 and b >= 0:
        return body[:a + len(GEN_BEGIN)] + block + body[b:]
    lines = body.split("\n")
    idx = next(i for i, l in enumerate(lines) if CHECKBOX.match(l))
    return "\n".join(lines[:idx + 1] + ["", GEN_BEGIN + block + GEN_END] + lines[idx + 1:])


def sorted_releases(vault):
    return sorted(vault.releases.values(), key=lambda r: (r["order"], r["id"]))


def task_sort(t):
    m = re.match(r"^[a-z]+-(\d+)", t["id"])
    return (0, int(m.group(1)), t["id"]) if m else (1, 0, t["id"])


def table(vault, tasks, d):
    rows = ["| Task | Title | State | Owner | Depends on | PRs |", "| --- | --- | --- | --- | --- | --- |"]
    for t in sorted(tasks, key=task_sort):
        deps = ", ".join(task_link(vault, x, d) + ("" if vault.accepted(x) else " (open)") for x in t["depends_on"])
        prs = ", ".join(f"[{short_ref(p)}]({gh_url(p).replace('/issues/', '/pull/')})" for p in t["prs"])
        title = t["title"].replace("|", "\\|")
        rows.append(f"| {task_link(vault, t['id'], d)} | {title} | {derived_state(vault, t)} | "
                    f"{t['owner'] or '—'} | {deps or '—'} | {prs or '—'} |")
    return "\n".join(rows)


def render_views(vault):
    out = {}
    views = vault.root / "views"
    open_tasks = [t for t in vault.tasks.values() if not t["done"]]
    by_state = {}
    for t in open_tasks:
        by_state.setdefault(derived_state(vault, t), []).append(t)

    lines = ["# Planning overview", "", GENERATED_NOTICE, "",
             "Read-only summary derived from the task notes. Edit the task notes, then run "
             "`python3 scripts/plan.py render`.", "",
             "States: **active**, **review** and **blocked** come from the card's status tag. For "
             "`#status/planned` the state is derived: **waiting** (a dependency is not accepted), **queued** "
             "(dependencies accepted, release not started) or **ready** (dependencies accepted and the release "
             "is active, or the task is explicitly pulled ahead with `early: true`). A ready task is not "
             "assigned work: the Maintainer still assigns it.", ""]
    lines += ["## Counts", "", "| State | Tasks |", "| --- | ---: |"]
    for st in ["active", "review", "blocked", "ready", "queued", "waiting", "backlog"]:
        lines.append(f"| {st} | {len(by_state.get(st, []))} |")
    lines.append(f"| closed | {sum(1 for t in vault.tasks.values() if t['done'])} |")
    lines.append("")
    for st, heading in [("active", "Active"), ("review", "Ready for review"), ("blocked", "Blocked"),
                        ("ready", "Ready to assign")]:
        lines += [f"## {heading}", ""]
        items = by_state.get(st, [])
        lines += [table(vault, items, views) if items else "None.", ""]
    lines += ["## By release", ""]
    for r in sorted_releases(vault):
        items = [t for t in open_tasks if t["release"] == r["id"]]
        closed = sum(1 for t in vault.tasks.values() if t["done"] and t["release"] == r["id"])
        lines.append(f"- {release_link(vault, r['id'], views)}: {r['title']} — {len(items)} open, {closed} closed "
                     f"([view](releases/{r['id']}.md))")
    lines.append("")
    out[views / "overview.md"] = "\n".join(lines)

    for r in sorted_releases(vault):
        d = views / "releases"
        items = [t for t in vault.tasks.values() if t["release"] == r["id"]]
        epics = [e for e in vault.epics.values() if e["release"] == r["id"]]
        lines = [f"# {r['id']} · {r['title']}", "", GENERATED_NOTICE, "",
                 f"Release note: {release_link(vault, r['id'], d)} · release status: **{r['status']}** "
                 "(maintained in the release note; task states never qualify a release).", ""]
        if epics:
            lines += ["Epics: " + ", ".join(f"{task_link(vault, e['id'], d)} {e['title']}" for e in
                                            sorted(epics, key=lambda e: e["id"])), ""]
        lines += [table(vault, items, d) if items else "No tasks.", ""]
        out[d / f"{r['id']}.md"] = "\n".join(lines)

    lines = ["# Epics", "", GENERATED_NOTICE, ""]
    for e in sorted(vault.epics.values(), key=lambda e: task_sort(e)):
        children = [t for t in vault.tasks.values() if t["parent"] == e["id"]]
        lines += [f"## {task_link(vault, e['id'], views)} · {e['title']}", "",
                  f"Status: {e['status']} · release: "
                  + (release_link(vault, e["release"], views) if e["release"] else "—"), ""]
        lines += [table(vault, children, views) if children else "No child tasks.", ""]
    out[views / "epics.md"] = "\n".join(lines)

    out[vault.root / "migration" / "manifest.json"] = json.dumps(build_manifest(vault), indent=2,
                                                                  ensure_ascii=False) + "\n"
    out[vault.root / "migration" / "coverage.md"] = render_coverage(vault)
    return out


def build_manifest(vault):
    inventory = json.loads((SNAPSHOT / "inventory.json").read_text(encoding="utf-8"))
    dests = {}
    for doc in sorted(vault.docs.values(), key=lambda d: vault.rel(d["path"])):
        for i, src in enumerate(doc["sources"]):
            dests.setdefault(src, []).append({
                "path": vault.rel(doc["path"]), "kind": doc["kind"], "role": "primary" if i == 0 else "additional"})
        for src in doc.get("aliases", []):
            dests.setdefault(src, []).append({"path": vault.rel(doc["path"]), "kind": doc["kind"], "role": "duplicate"})
    entries = []
    for e in inventory["open_issues"]:
        d = dests.get(e["source"], [])
        kinds = sorted({x["kind"] for x in d})
        if not d:
            disposition = "unmapped"
        elif len(d) > 1 and all(x["kind"] == "task" for x in d):
            disposition = "split"
        elif all(x["role"] == "duplicate" for x in d):
            disposition = "duplicate"
        else:
            disposition = "+".join(kinds)
        entries.append({"source": e["source"], "title": e["title"], "source_updated": e["updated_at"],
                        "snapshot": e["file"], "disposition": disposition, "destinations": d})
    return {"inventory_captured_at": inventory["captured_at"],
            "repositories": inventory["repositories"],
            "open_issue_count": len(entries),
            "mapped_count": sum(1 for x in entries if x["disposition"] != "unmapped"),
            "issues": entries,
            "open_pull_requests": [p["source"] for p in inventory["open_pull_requests"]]}


def render_coverage(vault):
    m = build_manifest(vault)
    lines = ["# Migration coverage", "", GENERATED_NOTICE, "",
             f"Source inventory captured {m['inventory_captured_at']} from: "
             + ", ".join(m["repositories"]) + ".", ""]
    per_repo = {}
    for e in m["issues"]:
        repo = e["source"].split("#")[0]
        per_repo.setdefault(repo, {"open": 0, "mapped": 0})
        per_repo[repo]["open"] += 1
        per_repo[repo]["mapped"] += e["disposition"] != "unmapped"
    lines += ["| Repository | Open issues | Mapped |", "| --- | ---: | ---: |"]
    for repo, c in per_repo.items():
        lines.append(f"| {repo} | {c['open']} | {c['mapped']} |")
    lines.append(f"| **Total** | **{m['open_issue_count']}** | **{m['mapped_count']}** |")
    lines += ["", "## Dispositions", "", "| Disposition | Count |", "| --- | ---: |"]
    counts = {}
    for e in m["issues"]:
        counts[e["disposition"]] = counts.get(e["disposition"], 0) + 1
    for k in sorted(counts):
        lines.append(f"| {k} | {counts[k]} |")
    lines += ["", "## Source to destination", "", "| Source | Disposition | Destination |", "| --- | --- | --- |"]
    for e in m["issues"]:
        dest = ", ".join(f"[{x['path']}](../{x['path']})" + (f" ({x['role']})" if x["role"] != "primary" else "")
                         for x in e["destinations"]) or "**unmapped**"
        lines.append(f"| [{short_ref(e['source'])}]({gh_url(e['source'])}) | {e['disposition']} | {dest} |")
    pr_doc = ("[pull-requests.md](pull-requests.md)" if (vault.root / "migration" / "pull-requests.md").exists()
              else "`migration/pull-requests.md`")
    lines += ["", f"Open pull requests at capture ({len(m['open_pull_requests'])}) are inspected separately in "
                  f"{pr_doc}; they stay in their code repositories.", ""]
    return "\n".join(lines)


def render(vault):
    changed = []
    for t in vault.tasks.values():
        text = t["path"].read_text(encoding="utf-8")
        head, body = text[:text.find("\n---\n", 4) + 5], text[text.find("\n---\n", 4) + 5:]
        new = head + apply_block(body, links_block(vault, t))
        if new != text:
            t["path"].write_text(new, encoding="utf-8")
            changed.append(t["path"])
    for path, content in render_views(vault).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            changed.append(path)
    for p in changed:
        print("updated", vault.rel(p))


